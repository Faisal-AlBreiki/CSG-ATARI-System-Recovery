create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  fragment integer not null check (fragment between 1 and 3),
  participant_id text not null,
  created_at timestamptz not null default now(),
  unique (fragment, participant_id)
);

alter table public.submissions enable row level security;

-- The client does not get direct table read/write access.
revoke all on table public.submissions from anon, authenticated;

create or replace function public.submit_answer(
  p_fragment integer,
  p_answer text,
  p_participant_id text
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  expected text;
  inserted boolean := false;
  current_count integer;
begin
  -- IMPORTANT:
  -- Replace these three values with the actual answers from your puzzles.
  expected := case p_fragment
    when 1 then 'CSG'
    when 2 then 'ATARI'
    when 3 then '2026'
  end;

  if upper(trim(p_answer)) <> upper(trim(expected)) then
    return json_build_object('correct', false, 'count', 0);
  end if;

  insert into public.submissions(fragment, participant_id)
  values (p_fragment, p_participant_id)
  on conflict (fragment, participant_id) do nothing;

  inserted := found;

  select count(*) into current_count
  from public.submissions
  where fragment = p_fragment;

  return json_build_object(
    'correct', true,
    'count', current_count,
    'new_operator', inserted
  );
end;
$$;

create or replace function public.get_progress()
returns table(fragment integer, count bigint, complete boolean)
language sql
security definer
set search_path = public
as $$
  select
    f.fragment,
    count(s.id) as count,
    (count(s.id) >= 3) as complete
  from generate_series(1,3) as f(fragment)
  left join public.submissions s on s.fragment = f.fragment
  group by f.fragment
  order by f.fragment;
$$;

grant execute on function public.submit_answer(integer, text, text) to anon, authenticated;
grant execute on function public.get_progress() to anon, authenticated;
